"""Build results/summary.md from the result files (plain python3, no sage needed).

usage: python3 summarize.py [results dir (default: results)] [Hou-Jiang Table 5.1 csv
       (default: ext/enhanced_lattice-estimator/FHE_paper_estimate_results.csv)]
"""
import collections, csv, json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "results")
HJ_CSV = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "ext", "enhanced_lattice-estimator", "FHE_paper_estimate_results.csv")

EST = ("usvp", "bdd", "bdd_hybrid", "bdd_mitm_hybrid", "dual", "dual_hybrid", "arora-gb", "bkw")
INF = float("inf")


def load(name):
    out = []
    p = os.path.join(RES, name)
    if os.path.exists(p):
        for l in open(p):
            if l.strip():
                out.append(json.loads(l))
    return out


def table(rows):
    R = collections.defaultdict(dict)
    for d in rows:
        b = d.get("bits")
        R[d["label"]][d["mode"]] = INF if b is None else b
    return R


K = table(load("keys.jsonl"))
T = table(load("tfhe_lwe.jsonl"))
HJ = table(load("hj_keys.jsonl"))
info = {d["label"]: d for d in load("keys.jsonl") + load("tfhe_lwe.jsonl")}


def f(x, nd=1):
    if x is None:
        return "–"
    return "inf" if x == INF else f"{x:.{nd}f}"


def standard(r):
    v = {a: r[f"est:{a}"] for a in EST if f"est:{a}" in r}
    if not v:
        return None, None, 0
    a = min(v, key=v.get)
    return v[a], a, len(v)



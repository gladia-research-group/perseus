def ogil(lab):
    r = K.get(lab, {})
    pre = "spru_rot_" if lab and "spru_b63" in lab else "rot_"
    return [r.get(pre + m) for m in ("nomitm", "h1", "h2")] if lab else [None] * 3


def std_of(lab):
    r = K.get(lab) or T.get(lab) or {}
    if "spru_mitm" in r:                      # block model: the plain primal hybrid is its "standard" attack
        return min(r["spru_mitm"], r.get("spru_nomitm", INF)), "plain hybrid, block model", 0
    return standard(r)


def row(key, sec, lab, olab, hlab, note):
    s, a, n = std_of(lab)
    o = ogil(olab)
    h = [HJ.get(hlab, {}).get(m) for m in ("egv", "ehg")] if hlab else [None, None]
    logq = info.get(lab, {}).get("logq")
    cand = [x for x in [s] + o + h if x is not None]
    mn = min(cand) if cand else None
    if note == "dense":
        hs = "n/a (dense)"
    elif note == "eq":
        hs = f"{f(h[0])} / {f(h[1])} (eq. modulus)"
    elif note == "no ring":
        hs = "n/a (no ring)"
    elif note == "not run":
        hs = "not run"
    else:
        hs = f"{f(h[0])} / {f(h[1])}"
    os_ = "n/a (no ring)" if note == "no ring" else ("≥ n32a4's (smaller q)" if olab is None and lab.startswith("dense") else " / ".join(f(x) for x in o))
    return f"| {key} | {sec}, {f(logq, 3) if logq else '–'} | {f(s, 2)} ({a}) | {os_} | {hs} | **{f(mn, 2)}** |"



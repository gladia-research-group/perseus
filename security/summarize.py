# ---------------------------------------------------------------- dense scans
w("\n## Exhaustive scans on the dense CKKS keys\n")
w("Every zeta from 0 up (3 shards), every hw, beta by the estimator's local minimum, d optimised; each shard stops at "
  "the first zeta whose proven lower bound LB(zeta) exceeds the best cost found (LB is non-decreasing in zeta). "
  "`stock` = the estimator's own zeta search (keys.jsonl) for the same attack.\n")
S = collections.defaultdict(lambda: {"best": None, "n": 0, "stops": [], "viol": 0})
for d in load("dense_scans.jsonl"):
    k = (d["label"], d["mode"])
    if "stop" in d:
        S[k]["stops"].append(d["stop"])
    elif d.get("bits") is not None:
        S[k]["n"] += 1
        if S[k]["best"] is None or d["bits"] < S[k]["best"][0]:
            S[k]["best"] = (d["bits"], d["zeta"])
        if d.get("lb") is not None and d["lb"] > d["bits"] + 1e-3:
            S[k]["viol"] += 1
STOCK = {"plain_cvp": "est:bdd_hybrid", "plain_mitm": "est:bdd_mitm_hybrid"}
w("| key | mode | scan min | at zeta | zetas evaluated | shard stops | LB > cost | stock |\n|---|---|---|---|---|---|---|---|")
